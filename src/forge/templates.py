EXIT_GATE = "【本期出口】贴出 `git diff --stat`，待回复「继续」后才进入下一期。"


def build_missing_hint(slot, question):
    """生成缺失槽位的人工确认提示。"""
    return "%s %s：%s" % (PLACEHOLDER, slot, question)
